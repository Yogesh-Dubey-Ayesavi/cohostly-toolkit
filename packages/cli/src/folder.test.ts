import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { deployFields, hasSnapshot, readSnapshot, stageSource } from './snapshot-folder.js';
import { bundledTool, captureBinary } from './vendor.js';
import { describeEnv, sealEnv } from './snapshot/sealed-env.js';
import { generateKeyPairSync } from 'node:crypto';
import { sealFailureMessage } from './commands/folder.js';

const SECRET = 'sk-live-value-that-must-stay-in-the-request-body';
const GENERATED = '# Generated by `cohostly snapshot`.\nFROM node:22-slim\nWORKDIR /app\nCOPY . .\nRUN npm install\n';

/** An app folder with the snapshot `cohostly snapshot` leaves in .cohostly/. */
function appWithSnapshot(o: { todo?: string; warning?: string; note?: string; port?: number | null; ownDockerfile?: boolean } = {}): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'snap-test-'));
  fs.writeFileSync(path.join(dir, 'package.json'), '{"scripts":{"start":"node server.js"}}');
  fs.writeFileSync(path.join(dir, 'server.js'), 'console.log(1)');
  fs.writeFileSync(path.join(dir, '.env'), `API_KEY=${SECRET}`);
  fs.mkdirSync(path.join(dir, 'node_modules/x'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'node_modules/x/index.js'), 'x');
  if (o.ownDockerfile) fs.writeFileSync(path.join(dir, 'Dockerfile'), 'FROM my-own-base\n');
  const snap = path.join(dir, '.cohostly');
  fs.mkdirSync(snap);
  fs.writeFileSync(path.join(snap, 'cohostly.json'), JSON.stringify({
    name: 'my-app', runtime: { language: 'dockerfile', entrypoint: 'npm start' },
    health: { ...(o.port === null ? {} : { port: o.port ?? 3000 }), path: '/health' }, env: { secrets: ['API_KEY', 'NOT_SET'] },
  }));
  fs.writeFileSync(path.join(snap, 'Dockerfile'), (o.todo ? `# TODO(cohostly): ${o.todo}\n` : '') + (o.warning ? `# WARNING(cohostly): ${o.warning}\n` : '') + (o.note ? `# NOTE(cohostly): ${o.note}\n` : '') + GENERATED);
  fs.writeFileSync(path.join(snap, 'env.json'), JSON.stringify({ API_KEY: { value: SECRET, source: '.env' } }));
  return dir;
}

function listing(tgz: Buffer): string {
  const f = path.join(os.tmpdir(), `snap-test-${process.pid}-${Math.random().toString(36).slice(2)}.tgz`);
  fs.writeFileSync(f, tgz);
  try { return execFileSync('tar', ['-tzf', f], { encoding: 'utf8' }); } finally { fs.rmSync(f, { force: true }); }
}
function fileIn(tgz: Buffer, name: string): string {
  const f = path.join(os.tmpdir(), `snap-test-${process.pid}-${Math.random().toString(36).slice(2)}.tgz`);
  fs.writeFileSync(f, tgz);
  try {
    // GNU tar and bsdtar disagree on whether the member is stored as "./name" or "name", so ask the archive which.
    const member = execFileSync('tar', ['-tzf', f], { encoding: 'utf8' }).split('\n').find((m) => m === name || m === `./${name}`);
    return execFileSync('tar', ['-xzOf', f, member ?? name], { encoding: 'utf8' });
  } finally { fs.rmSync(f, { force: true }); }
}

test('a folder is a snapshot only when it has the settings file', () => {
  assert.equal(hasSnapshot(appWithSnapshot()), true);
  assert.equal(hasSnapshot(fs.mkdtempSync(path.join(os.tmpdir(), 'snap-test-'))), false);
});

test('the upload carries the app and the generated Dockerfile, but never the snapshot folder, dependencies or .env', () => {
  const dir = appWithSnapshot();
  const tgz = stageSource(dir, readSnapshot(dir));
  const files = listing(tgz);
  assert.match(files, /Dockerfile/);
  assert.match(files, /server\.js/);
  for (const bad of [/\.cohostly/, /env\.json/, /node_modules/, /\.env/]) assert.doesNotMatch(files, bad);
  assert.equal(fileIn(tgz, 'Dockerfile'), GENERATED);
});

test('a Dockerfile in the project root is the developer\'s and is deployed as it is', () => {
  const dir = appWithSnapshot({ ownDockerfile: true });
  const s = readSnapshot(dir);
  assert.equal(s.own, true);
  assert.equal(fileIn(stageSource(dir, s), 'Dockerfile'), 'FROM my-own-base\n');
});

test('asking for the generated Dockerfile replaces the developer\'s', () => {
  const dir = appWithSnapshot({ ownDockerfile: true });
  assert.equal(fileIn(stageSource(dir, readSnapshot(dir), true), 'Dockerfile'), GENERATED);
});

test('captured values travel only in the secrets field, and a name nobody gave a value for is not sent', () => {
  const dir = appWithSnapshot();
  const f = deployFields(readSnapshot(dir), 'my-app');
  assert.deepEqual(JSON.parse(f.secrets), { API_KEY: SECRET });
  assert.doesNotMatch(f.manifest, new RegExp(SECRET));
  const m = JSON.parse(f.manifest);
  assert.equal(m.health.port, 3000);
  assert.equal(m.runtime.language, 'dockerfile');
});

test('the settings are sent as the developer left them, with only the project name decided by the flag', () => {
  const dir = appWithSnapshot();
  const file = path.join(dir, '.cohostly', 'cohostly.json');
  fs.writeFileSync(file, JSON.stringify({ ...JSON.parse(fs.readFileSync(file, 'utf8')), visibility: 'private' }));
  const m = JSON.parse(deployFields(readSnapshot(dir), 'renamed').manifest);
  assert.equal(m.visibility, 'private');
  assert.equal(m.name, 'renamed');
});

test('questions the tool left in the Dockerfile are reported, so the deploy can stop before uploading', () => {
  const s = readSnapshot(appWithSnapshot({ todo: 'Which port does the app serve on?' }));
  assert.deepEqual(s.open, ['Which port does the app serve on?']);
  assert.deepEqual(readSnapshot(appWithSnapshot()).open, []);
});

test('no snapshot, or one with no port, says what to do', () => {
  assert.throws(() => readSnapshot(fs.mkdtempSync(path.join(os.tmpdir(), 'snap-test-'))), /cohostly snapshot -- /);
  assert.throws(() => readSnapshot(appWithSnapshot({ port: null })), /no health\.port/);
});

test('tools are found in the CLI bundle for this platform, or the error says how to get one', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vendor-test-'));
  fs.mkdirSync(path.join(root, 'darwin-arm64'));
  fs.writeFileSync(path.join(root, 'darwin-arm64', 'cohostly-capture'), '');
  const here = { platform: 'darwin', arch: 'arm64', root };
  assert.equal(bundledTool('cohostly-capture', here), path.join(root, 'darwin-arm64', 'cohostly-capture'));
  assert.equal(bundledTool('railpack', here), null);
  assert.equal(captureBinary({}, here), path.join(root, 'darwin-arm64', 'cohostly-capture'));
  assert.throws(() => captureBinary({}, { ...here, platform: 'linux' }), /make capture-bin/);
  assert.throws(() => captureBinary({ COHOSTLY_CAPTURE: '/nope/missing' }, here), /does not exist/);
});

test('sealed values are not readable in env.enc, and say whose they are and when they expire', () => {
  const { publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });
  const text = sealEnv({ key: { key_id: 'k1', public_key_pem: publicKey.export({ type: 'spki', format: 'pem' }).toString() }, accountId: 'acc-1', expiresAt: new Date('2030-01-01'), values: { API_KEY: SECRET } });
  assert.ok(!text.includes(SECRET));
  assert.deepEqual(describeEnv(text), { accountId: 'acc-1', expiresAt: '2030-01-01T00:00:00.000Z' });
  assert.throws(() => describeEnv('{"format":"nope"}'), /not an env\.enc/);
});

test('a snapshot with only env.enc deploys the sealed text and no plain values', () => {
  const dir = appWithSnapshot();
  fs.rmSync(path.join(dir, '.cohostly', 'env.json'));
  fs.writeFileSync(path.join(dir, '.cohostly', 'env.enc'), '{"format":"cohostly-env/1"}');
  const f = deployFields(readSnapshot(dir), 'my-app');
  assert.equal(f.sealed_env, '{"format":"cohostly-env/1"}');
  assert.equal(f.secrets, undefined);
});

test('plain values win over a stale env.enc, so a fresh snapshot is what deploys', () => {
  const dir = appWithSnapshot();
  fs.writeFileSync(path.join(dir, '.cohostly', 'env.enc'), '{"format":"cohostly-env/1"}');
  const f = deployFields(readSnapshot(dir), 'my-app');
  assert.equal(f.sealed_env, undefined);
  assert.deepEqual(JSON.parse(f.secrets), { API_KEY: SECRET });
});

test('a variable with no value is a note that does not stop the deploy, while a question does', () => {
  const s = readSnapshot(appWithSnapshot({ note: 'NOT_SET has no value here.', todo: 'Which port?' }));
  assert.deepEqual(s.notes, ['NOT_SET has no value here.']);
  assert.deepEqual(s.open, ['Which port?']);
  assert.deepEqual(readSnapshot(appWithSnapshot({ note: 'NOT_SET has no value here.' })).open, []);
});

test('a warning is shown and never stops the deploy', () => {
  const s = readSnapshot(appWithSnapshot({ warning: 'The app listens on 127.0.0.1 only.' }));
  assert.deepEqual(s.warnings, ['The app listens on 127.0.0.1 only.']);
  assert.deepEqual(s.open, []);
});

test('a sealing failure names the server it could not reach and says what to set', () => {
  const offline = Object.assign(new TypeError('fetch failed'), { cause: { code: 'ECONNREFUSED' } });
  const msg = sealFailureMessage(offline, 'http://localhost:8080');
  assert.match(msg, /Could not reach http:\/\/localhost:8080 \(ECONNREFUSED\)/);
  assert.match(msg, /API_URL/);
  assert.match(msg, /env\.json now holds them in plain text/);
});

test('a sealing failure the server explained is shown as the server worded it', () => {
  const msg = sealFailureMessage(new Error('You are not signed in. Run "cohostly login", then try again.'), 'https://api.cohostly.cloud');
  assert.match(msg, /not signed in/);
  assert.doesNotMatch(msg, /Could not reach/);
});
